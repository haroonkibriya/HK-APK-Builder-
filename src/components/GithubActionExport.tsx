import React, { useState } from 'react';
import { Copy, Check, Download, FileCode } from 'lucide-react';
import { BuildConfig } from '../types';

interface GithubActionExportProps {
  config: BuildConfig;
}

export const GithubActionExport: React.FC<GithubActionExportProps> = ({ config }) => {
  const [copied, setCopied] = useState(false);

  const workflowYaml = `# Automated APK Build Workflow generated by HK APK Builder
# App: ${config.appName}
# Target Live URL: ${config.webUrl}

name: Build Android APK

on:
  workflow_dispatch:
  push:
    branches: [ main, master ]

jobs:
  build-apk:
    name: Build ${config.appName} APK
    runs-on: ubuntu-latest

    steps:
      - name: Checkout Repository
        uses: actions/checkout@v4

      - name: Setup Java JDK 17
        uses: actions/setup-java@v4
        with:
          distribution: 'temurin'
          java-version: '17'

      - name: Setup Android SDK
        uses: android-actions/setup-android@v3

      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '20'
          cache: 'npm'

      - name: Install Dependencies
        run: |
          npm install -g @capacitor/cli @capacitor/core @capacitor/android
          npm install

      - name: Configure Capacitor Android Shell
        run: |
          npx cap add android || true
          cat << 'EOF' > capacitor.config.json
{
  "appId": "${config.packageName}",
  "appName": "${config.appName}",
  "webDir": "dist",
  "server": {
    "url": "${config.webUrl}",
    "cleartext": true
  }
}
EOF
          npx cap sync android

      - name: Build Debug APK with Gradle
        working-directory: android
        run: |
          chmod +x ./gradlew
          ./gradlew assembleDebug --stacktrace

      - name: Upload APK Artifact
        uses: actions/upload-artifact@v4
        with:
          name: ${config.appName.replace(/\s+/g, '-')}-v${config.versionName}.apk
          path: android/app/build/outputs/apk/debug/app-debug.apk
          retention-days: 14
`;

  const handleCopy = () => {
    navigator.clipboard.writeText(workflowYaml);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([workflowYaml], { type: 'text/yaml' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'build-apk.yml';
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="bg-[#0F172A] border border-slate-800 rounded-xl p-4">
      <div className="flex items-center justify-between mb-3">
        <div className="flex items-center gap-2">
          <FileCode className="w-4 h-4 text-cyan-400" />
          <span className="text-xs font-bold text-slate-200">.github/workflows/build-apk.yml</span>
        </div>
        <div className="flex gap-2">
          <button
            onClick={handleCopy}
            className="flex items-center gap-1.5 px-2.5 py-1 bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs rounded border border-slate-700 transition"
          >
            {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
            <span>{copied ? 'Copied' : 'Copy'}</span>
          </button>
          <button
            onClick={handleDownload}
            className="flex items-center gap-1.5 px-2.5 py-1 bg-blue-600 hover:bg-blue-500 text-white text-xs rounded transition"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download</span>
          </button>
        </div>
      </div>
      <pre className="text-[10px] font-mono text-slate-400 max-h-48 overflow-y-auto p-3 bg-slate-950 rounded-lg border border-slate-800/80">
        {workflowYaml}
      </pre>
    </div>
  );
};
